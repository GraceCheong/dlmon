export interface TokenResult {
  text: string;
  pinyin: string | null;
  hskLevel: number | null;
  meaning?: string;
}

export function getHSKLevel(word: string): number | null {
  for (const [level, wordSet] of Object.entries(HSK_SETS)) {
    if (wordSet.has(word)) return Number(level);
  }
  return null;
}

/**
 * Segment Chinese text with greedy longest-match + pinyin/HSK lookup
 */
export function segmentAndAnalyze(text: string): TokenResult[] {
  const tokens: TokenResult[] = [];
  let i = 0;
  while (i < text.length) {
    const char = text[i];
    const isChinese = /[\u4e00-\u9fa5]/.test(char);
    if (!isChinese) {
      tokens.push({ text: char, pinyin: null, hskLevel: null });
      i++;
      continue;
    }
    let matched = false;
    for (let len = 4; len >= 2; len--) {
      if (i + len > text.length) continue;
      const word = text.substring(i, i + len);
      const hsk = getHSKLevel(word);
      const pinyin = PINYIN_MAP[word] || null;
      if (hsk !== null || pinyin !== null) {
        tokens.push({ text: word, pinyin, hskLevel: hsk });
        i += len;
        matched = true;
        break;
      }
    }
    if (!matched) {
      tokens.push({ text: char, pinyin: PINYIN_MAP[char] || null, hskLevel: getHSKLevel(char) });
      i++;
    }
  }
  return tokens;
}
